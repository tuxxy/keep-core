// Ties the tbtc-v2 FIXTURE artifacts to the pinned tbtc-v2 tree (review N4).
//
// For each artifact the C-11b world loads: the artifact's bytecode must equal
// its build-info output, and every source in that build-info must equal the
// pinned tree's blob (project sources, compared by git blob hash) or the
// checkout's installed dependency file (`@`-prefixed sources). A stale or
// locally edited build therefore fails before any case runs.
//
// CLI: node check-tbtc-build.js <tbtc-v2 root> <tree>  (checks WORLD_ARTIFACTS)
const fs = require("fs")
const path = require("path")
const crypto = require("crypto")
const { execFileSync } = require("child_process")

/// Every tbtc-v2 artifact the C-11b world reads (source, contract name).
const WORLD_ARTIFACTS = [
  ["contracts/bank/Bank.sol", "Bank"],
  ["contracts/bridge/Bridge.sol", "Bridge"],
  ["contracts/bridge/BridgeGovernance.sol", "BridgeGovernance"],
  ["contracts/frost/IFrostBridge.sol", "IFrostBridge"],
  ["@openzeppelin/contracts/proxy/transparent/ProxyAdmin.sol", "ProxyAdmin"],
  [
    "@openzeppelin/contracts/proxy/transparent/TransparentUpgradeableProxy.sol",
    "TransparentUpgradeableProxy",
  ],
]

function gitBlob(content) {
  const body = Buffer.from(content, "utf8")
  return crypto
    .createHash("sha1")
    .update(Buffer.concat([Buffer.from(`blob ${body.length}\0`), body]))
    .digest("hex")
}

function treeBlobs(root, tree) {
  const out = execFileSync(
    "git",
    ["-C", root, "ls-tree", "-r", tree, "--", "solidity"],
    { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 }
  )
  const blobs = new Map()
  out.split("\n").forEach((line) => {
    const m = line.match(/^\d+ blob ([0-9a-f]{40})\tsolidity\/(.*)$/)
    if (m) blobs.set(m[2], m[1])
  })
  return blobs
}

/// Throws on the first mismatch; returns the number of sources checked.
function checkTbtcBuild(root, tree, artifacts = WORLD_ARTIFACTS) {
  const sol = path.join(root, "solidity")
  const blobs = treeBlobs(root, tree)
  const infos = new Map()
  const problems = []
  artifacts.forEach(([source, name]) => {
    const dir = path.join(sol, "build", source)
    const artifact = JSON.parse(
      fs.readFileSync(path.join(dir, `${name}.json`), "utf8")
    )
    const dbg = JSON.parse(
      fs.readFileSync(path.join(dir, `${name}.dbg.json`), "utf8")
    )
    const infoPath = path.resolve(dir, dbg.buildInfo)
    if (!infos.has(infoPath)) {
      infos.set(infoPath, JSON.parse(fs.readFileSync(infoPath, "utf8")))
    }
    const info = infos.get(infoPath)
    const out =
      info.output.contracts[source] && info.output.contracts[source][name]
    if (!out) {
      problems.push(`${source}:${name} is not in its build-info`)
      return
    }
    if (
      `0x${out.evm.bytecode.object}`.toLowerCase() !==
      String(artifact.bytecode).toLowerCase()
    ) {
      problems.push(
        `${source}:${name} artifact bytecode differs from its build-info`
      )
    }
  })
  let checked = 0
  infos.forEach((info, infoPath) => {
    Object.entries(info.input.sources).forEach(([source, { content }]) => {
      checked += 1
      if (source.startsWith("@")) {
        const file = path.join(sol, "node_modules", source)
        if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== content) {
          problems.push(
            `${path.basename(
              infoPath
            )}: dependency ${source} differs from node_modules`
          )
        }
        return
      }
      const stub = source.match(
        /^contracts\/hardhat-dependency-compiler\/(.*)$/
      )
      if (stub) {
        // Generated by hardhat-dependency-compiler (gitignored): exactly the
        // plugin's three-line import stub of the dependency.
        const expected = `// SPDX-License-Identifier: UNLICENSED\npragma solidity >0.0.0;\nimport '${stub[1]}';\n`
        if (content !== expected && content !== expected.trimEnd()) {
          problems.push(
            `${path.basename(
              infoPath
            )}: ${source} is not the dependency-compiler stub`
          )
        }
        return
      }
      const want = blobs.get(source)
      if (want !== gitBlob(content)) {
        problems.push(
          `${path.basename(infoPath)}: ${source} ${
            want ? "differs from" : "is not in"
          } the pinned tree ${tree}`
        )
      }
    })
  })
  if (problems.length > 0) {
    throw new Error(
      `tbtc-v2 build is not from the pinned tree (rebuild ${sol}):\n  ${problems
        .slice(0, 10)
        .join("\n  ")}`
    )
  }
  return checked
}

module.exports = { checkTbtcBuild, WORLD_ARTIFACTS }

if (require.main === module) {
  const [root, tree] = process.argv.slice(2)
  const n = checkTbtcBuild(root, tree)
  console.log(`tbtc-v2 build matches tree ${tree} (${n} sources)`)
}
